export function getLocalizedScheme(scheme: Scheme, language: Language): Scheme {
  if (language === 'en') return scheme;

  const langKey = language as 'hi' | 'mr';
  const customTrans = SCHEME_TRANSLATIONS[langKey]?.[scheme.id];

  // Localized Documents
  const docDict = COMMON_DOCUMENTS[langKey] || {};
  const localizedDocs = scheme.required_documents.map(
    (doc, idx) => customTrans?.required_documents?.[idx] || docDict[doc] || translateTextSimple(doc, langKey)
  );

  return {
    ...scheme,
    name: customTrans?.name || translateTextSimple(scheme.name, langKey),
    category: scheme.category,
    ministry: customTrans?.ministry || translateTextSimple(scheme.ministry, langKey),
    short_description: customTrans?.short_description || translateTextSimple(scheme.short_description, langKey),
    full_description: customTrans?.full_description || translateTextSimple(scheme.full_description, langKey),
    benefits: customTrans?.benefits || scheme.benefits.map((b) => translateTextSimple(b, langKey)),
    eligibility: {
      ...scheme.eligibility,
      age_limit: customTrans?.eligibility?.age_limit || translateTextSimple(scheme.eligibility.age_limit || '', langKey),
      income_limit: customTrans?.eligibility?.income_limit || translateTextSimple(scheme.eligibility.income_limit || '', langKey),
      gender: customTrans?.eligibility?.gender || translateTextSimple(scheme.eligibility.gender || '', langKey),
      occupation: customTrans?.eligibility?.occupation || translateTextSimple(scheme.eligibility.occupation || '', langKey),
      state: customTrans?.eligibility?.state || translateTextSimple(scheme.eligibility.state || '', langKey),
      exclusions: customTrans?.eligibility?.exclusions || translateTextSimple(scheme.eligibility.exclusions || '', langKey),
    },
    required_documents: localizedDocs,
    application_steps: customTrans?.application_steps || scheme.application_steps.map((s) => translateTextSimple(s, langKey)),
    notes: scheme.notes ? (customTrans?.notes || translateTextSimple(scheme.notes, langKey)) : undefined,
  };
}
